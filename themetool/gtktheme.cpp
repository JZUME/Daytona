QString findChicago95GtkCss()
{
    return QStandardPaths::locate(
        QStandardPaths::GenericDataLocation, QStringLiteral("themes/Chicago95/gtk-3.0/gtk.css"));
}

QByteArray gtkCss(const SchemeColours &colours, const QString &chicagoCss)
{
    QByteArray css = "/* Generated by daytona-themetool from a Windows colour scheme.\n"
                     " * Changes are overwritten by the next daytona-themetool apply. */\n\n";
    css += "@import url(\"" + QUrl::fromLocalFile(chicagoCss).toEncoded() + "\");\n\n";
    for (const auto &[gtkName, key] : GtkColours) {
        css += QByteArray("@define-color ") + gtkName + ' '
            + colourOf(colours, key).name(QColor::HexRgb).toLatin1() + ";\n";
    }
    return css;
}

QString gtkUserThemeDir()
{
    return QDir(xdgHome("XDG_DATA_HOME", QStringLiteral("/.local/share")))
        .filePath(QStringLiteral("themes/Daytona/gtk-3.0"));
}

bool writeGtkTheme(
    const QString &dir, const SchemeColours &colours, const QString &chicagoCss, QString *error)
{
    if (chicagoCss.isEmpty()) {
        if (error)
            *error = QStringLiteral("the Chicago95 GTK theme is not installed");
        return false;
    }
    const QDir target(dir);
    if (target.exists() && !target.isEmpty() && !QFileInfo::exists(target.filePath(MarkerName))) {
        if (error)
            *error = QStringLiteral("%1 holds a theme Daytona did not generate; leaving it alone")
                         .arg(dir);
        return false;
    }
    if (!QDir().mkpath(dir)) {
        if (error)
            *error = QStringLiteral("Cannot create %1").arg(dir);
        return false;
    }
    return writeFile(target.filePath(MarkerName), "Generated by daytona-themetool.\n", error)
        && writeFile(
            target.filePath(QStringLiteral("gtk.css")), gtkCss(colours, chicagoCss), error);
}

bool removeGtkTheme(const QString &dir, QString *error)
{
    const QDir target(dir);
    if (!QFileInfo::exists(target.filePath(MarkerName)))
        return true;
    for (const QString &name : { QStringLiteral("gtk.css"), MarkerName }) {
        const QString path = target.filePath(name);
        if (QFileInfo::exists(path) && !QFile::remove(path)) {
            if (error)
                *error = QStringLiteral("Cannot remove %1").arg(path);
            return false;
        }
    }
    QDir().rmdir(dir);
    QDir().rmdir(QFileInfo(dir).absolutePath());
    return true;
}

QString gtkSettingsPath()
{
    return QDir(xdgHome("XDG_CONFIG_HOME", QStringLiteral("/.config")))
        .filePath(QStringLiteral("gtk-3.0/settings.ini"));
}

bool setGtkSettings(
    const QString &path, const QString &iconTheme, const QString &cursorTheme, QString *error)
{
    return setGtkSettingValues(path,
        { { "gtk-icon-theme-name", iconTheme.toUtf8() },
            { "gtk-cursor-theme-name", cursorTheme.toUtf8() } },
        error);
}

bool setGtkCursorSettings(const QString &path, const QString &cursorTheme, int size, QString *error)
{
    return setGtkSettingValues(path,
        { { "gtk-cursor-theme-name", cursorTheme.toUtf8() },
            { "gtk-cursor-theme-size", QByteArray::number(size) } },
        error);
}

bool setGtkSettingValues(
    const QString &path, const QList<QPair<QByteArray, QByteArray>> &wanted, QString *error)
{
    QByteArray original;
    QFile in(path);
    if (in.exists()) {
        // settings.ini is a few lines; refuse anything unreasonable.
        if (!in.open(QIODevice::ReadOnly) || in.size() > 1024 * 1024) {
            if (error)
                *error = QStringLiteral("Cannot read %1").arg(path);
            return false;
        }
        original = in.readAll();
        in.close();
    } else if (!QDir().mkpath(QFileInfo(path).absolutePath())) {
        if (error)
            *error = QStringLiteral("Cannot create %1").arg(QFileInfo(path).absolutePath());
        return false;
    }

    // Edit the [Settings] group line by line so comments and other keys stay.
    QList<QByteArray> lines = original.split('\n');
    if (!lines.isEmpty() && lines.last().isEmpty())
        lines.removeLast();
    int settingsStart = -1;
    int settingsEnd = lines.size();
    for (int i = 0; i < lines.size(); ++i) {
        const QByteArray line = lines[i].trimmed();
        if (line.startsWith('[')) {
            if (settingsStart >= 0) {
                settingsEnd = i;
                break;
            }
            if (line == "[Settings]")
                settingsStart = i;
        }
    }
    if (settingsStart < 0) {
        if (!lines.isEmpty())
            lines << QByteArray();
        lines << QByteArray("[Settings]");
        settingsStart = lines.size() - 1;
        settingsEnd = lines.size();
    }
    for (const auto &[key, value] : wanted) {
        bool found = false;
        for (int i = settingsStart + 1; i < settingsEnd; ++i) {
            const QByteArray line = lines[i].trimmed();
            const int eq = line.indexOf('=');
            if (eq > 0 && line.left(eq).trimmed() == key) {
                lines[i] = key + '=' + value;
                found = true;
            }
        }
        if (!found) {
            // Insert after the last non-blank line of the group.
            int at = settingsEnd;
            while (at > settingsStart + 1 && lines[at - 1].trimmed().isEmpty())
                --at;
            lines.insert(at, key + '=' + value);
            ++settingsEnd;
        }
    }
    const QByteArray updated = lines.join('\n') + '\n';
    if (updated == original)
        return true; // nothing to change; leave the file alone
    const QString backup = path + QStringLiteral(".daytona-backup");
    if (QFileInfo::exists(path) && !QFileInfo::exists(backup)
        && !writeFile(backup, original, error))
        return false;
    return writeFile(path, updated, error);
}

