    QColor colourOf(const SchemeColours &colours, const char *key)
    {
        const QString name = QString::fromLatin1(key);
        const QColor colour = colours.value(name);
        return colour.isValid() ? colour : standardColours().value(name);
    }

    bool writeFile(const QString &path, const QByteArray &data, QString *error)
    {
        QSaveFile file(path);
        if (file.open(QIODevice::WriteOnly) && file.write(data) == data.size() && file.commit())
            return true;
        if (error)
            *error = QStringLiteral("%1: %2").arg(path, file.errorString());
        return false;
    }

    QString xdgHome(const char *variable, const QString &fallback)
    {
        const QString value = qEnvironmentVariable(variable);
        return value.isEmpty() ? QDir::homePath() + fallback : value;
    }

