namespace {

    // Marks a theme directory as generated, so only those are ever replaced
    // or removed.
    const QString MarkerName = QStringLiteral(".daytona-generated");

    const char *const Buttons[] = { "close", "iconify", "max", "max_toggled" };

    // Each file name a button's image is written under, for a template:
    // "close" -> close-active.svg, close_hover-active.svg and so on, and
    // "close_pressed" -> close_pressed-active.svg and close_pressed-inactive.svg.
    // NT buttons have no hover effect, so the hover images are the normal ones.
    QStringList buttonFileNames(const QString &image)
    {
        QStringList names;
        const bool pressed = image.endsWith(QLatin1String("_pressed"));
        for (const char *variant : { "", "_hover" }) {
            if (pressed && *variant)
                continue;
            for (const char *state : { "active", "inactive" })
                names << QStringLiteral("%1%2-%3.svg")
                             .arg(image, QLatin1String(variant), QLatin1String(state));
        }
        return names;
    }

    // Every button image template: each button and its pressed form.
    QStringList buttonImages()
    {
        QStringList images;
        for (const char *button : Buttons)
            images << QLatin1String(button) << QLatin1String(button) + QStringLiteral("_pressed");
        return images;
    }

    QString hex(const QColor &colour)
    {
        return colour.name(QColor::HexRgb);
    }

    QColor colourOf(const SchemeColours &colours, const char *key)
    {
        const QString name = QString::fromLatin1(key);
        const QColor colour = colours.value(name);
        return colour.isValid() ? colour : standardColours().value(name);
    }

    QByteArray templateFile(const QString &name)
    {
        QFile file(QStringLiteral(":/labwc-theme/") + name);
        if (!file.open(QIODevice::ReadOnly))
            qFatal("Built-in labwc theme template %s is missing", qPrintable(name));
        return file.readAll();
    }

    bool writeFile(const QString &path, const QByteArray &data, QString *error)
    {
        QSaveFile file(path);
        if (file.open(QIODevice::WriteOnly) && file.write(data) == data.size() && file.commit())
            return true;
        if (error)
            *error = QStringLiteral("%1: %2").arg(path, file.errorString());
        return false;
    }

    // Every file a generated theme consists of.
    QStringList themeFiles()
    {
        QStringList files { QStringLiteral("themerc") };
        for (const QString &image : buttonImages())
            files << buttonFileNames(image);
        return files;
    }

} // namespace

QByteArray labwcThemerc(const SchemeColours &colours)
{
    // themerc key -> Windows colour key(s).
    const QList<QPair<const char *, QList<const char *>>> map = {
        { "window.active.border.color", { "ActiveBorder" } },
        { "window.inactive.border.color", { "InactiveBorder" } },
        { "window.active.indicator.toggled-keybind.color", { "ActiveBorder" } },
        // The raised frame (Daytona's labwc patch): NT draws window frames
        // with the 3D button colours.
        { "window.border.bevel.light.color", { "ButtonLight" } },
        { "window.border.bevel.highlight.color", { "ButtonHilight" } },
        { "window.border.bevel.shadow.color", { "ButtonShadow" } },
        { "window.border.bevel.darkshadow.color", { "ButtonDkShadow" } },
        { "window.active.title.bg.color", { "ActiveTitle" } },
        { "window.inactive.title.bg.color", { "InactiveTitle" } },
        // Windows 98/2000 title bar gradients (Daytona's labwc patch).
        { "window.active.title.bg.colorTo", { "GradientActiveTitle" } },
        { "window.inactive.title.bg.colorTo", { "GradientInactiveTitle" } },
        { "window.active.label.text.color", { "TitleText" } },
        { "window.inactive.label.text.color", { "InactiveTitleText" } },
        { "menu.border.color", { "ButtonShadow" } },
        { "menu.items.bg.color", { "Menu" } },
        { "menu.items.text.color", { "MenuText" } },
        { "menu.items.active.bg.color", { "Hilight" } },
        { "menu.items.active.text.color", { "HilightText" } },
        { "menu.separator.color", { "ButtonShadow" } },
        { "menu.title.bg.color", { "ActiveTitle" } },
        { "menu.title.text.color", { "TitleText" } },
        { "osd.bg.color", { "ButtonFace" } },
        { "osd.border.color", { "ButtonShadow" } },
        { "osd.label.text.color", { "ButtonText" } },
        { "osd.window-switcher.preview.border.color",
            { "ButtonDkShadow", "ButtonHilight", "ButtonDkShadow" } },
    };

    QByteArray out = "# Generated by daytona-themetool from a Windows colour scheme.\n"
                     "# Changes are overwritten by the next daytona-themetool apply.\n";
    const QList<QByteArray> lines = templateFile(QStringLiteral("themerc")).split('\n');
    for (int i = 0; i < lines.size(); ++i) {
        const QByteArray &line = lines[i];
        if (i == lines.size() - 1 && line.isEmpty())
            break;
        const int colon = line.indexOf(':');
        const QByteArray key = colon > 0 ? line.left(colon).trimmed() : QByteArray();
        // A gradient only where the scheme gives the title bar two colours,
        // so NT schemes (Gradient = base colour) stay solid.
        if (key == "window.active.title.bg" || key == "window.inactive.title.bg") {
            const bool active = key == "window.active.title.bg";
            out += key
                + (titleBarHasGradient(colours, active) ? ": Gradient Horizontal\n" : ": Solid\n");
            continue;
        }
        bool replaced = false;
        for (const auto &[themeKey, schemeKeys] : map) {
            if (key != themeKey)
                continue;
            QStringList values;
            for (const char *schemeKey : schemeKeys)
                values << hex(colourOf(colours, schemeKey));
            out += key + ": " + values.join(QLatin1Char(',')).toLatin1() + '\n';
            replaced = true;
            break;
        }
        if (!replaced)
            out += line + '\n';
    }
    return out;
}

QByteArray labwcButtonSvg(const QString &buttonName, const SchemeColours &colours)
{
    // The template's NT colours, by the Windows key each one stands for.
    // Black is both the outer shadow and the glyph: the glyph is drawn in
    // single pixels, the shadow in lines.
    const QMap<QString, QString> fills = {
        { QStringLiteral("#c0c0c0"), hex(colourOf(colours, "ButtonFace")) },
        { QStringLiteral("#ffffff"), hex(colourOf(colours, "ButtonHilight")) },
        { QStringLiteral("#dfdfdf"), hex(colourOf(colours, "ButtonLight")) },
        { QStringLiteral("#808080"), hex(colourOf(colours, "ButtonShadow")) },
    };
    const QString dkShadow = hex(colourOf(colours, "ButtonDkShadow"));
    const QString text = hex(colourOf(colours, "ButtonText"));

    static const QRegularExpression rect(QStringLiteral("<rect [^>]*>"));
    static const QRegularExpression fill(QStringLiteral("fill=\"(#[0-9a-fA-F]{6})\""));
    static const QRegularExpression pixel(QStringLiteral("width=\"1\" height=\"1\""));

    QString svg = QString::fromUtf8(templateFile(buttonName + QStringLiteral(".svg")));
    QString result;
    qsizetype last = 0;
    QRegularExpressionMatchIterator it = rect.globalMatch(svg);
    while (it.hasNext()) {
        const QRegularExpressionMatch match = it.next();
        result += svg.mid(last, match.capturedStart() - last);
        QString element = match.captured();
        const QRegularExpressionMatch f = fill.match(element);
        if (f.hasMatch()) {
            const QString colour = f.captured(1).toLower();
            QString replacement = fills.value(colour);
            if (colour == QLatin1String("#000000"))
                replacement = pixel.match(element).hasMatch() ? text : dkShadow;
            if (!replacement.isEmpty())
                element.replace(f.capturedStart(1), f.capturedLength(1), replacement);
        }
        result += element;
        last = match.capturedEnd();
    }
    result += svg.mid(last);
    return result.toUtf8();
}

QString labwcUserThemeDir()
{
    QString base = qEnvironmentVariable("XDG_DATA_HOME");
    if (base.isEmpty())
        base = QDir::homePath() + QStringLiteral("/.local/share");
    return QDir(base).filePath(
        QStringLiteral("themes/%1/openbox-3").arg(QLatin1String(LabwcThemeName)));
}

bool writeLabwcTheme(const QString &dir, const SchemeColours &colours, QString *error)
{
    const QDir target(dir);
    // Never write over a theme the user put there themselves.
    if (target.exists() && !target.isEmpty() && !QFileInfo::exists(target.filePath(MarkerName))) {
        if (error)
            *error = QStringLiteral("%1 holds a theme Daytona did not generate; leaving it alone")
                         .arg(dir);
        return false;
    }
    if (!QDir().mkpath(dir)) {
        if (error)
            *error = QStringLiteral("Cannot create %1").arg(dir);
        return false;
    }
    if (!writeFile(target.filePath(MarkerName), "Generated by daytona-themetool.\n", error))
        return false;
    if (!writeFile(target.filePath(QStringLiteral("themerc")), labwcThemerc(colours), error))
        return false;
    for (const QString &image : buttonImages()) {
        const QByteArray svg = labwcButtonSvg(image, colours);
        for (const QString &name : buttonFileNames(image)) {
            if (!writeFile(target.filePath(name), svg, error))
                return false;
        }
    }
    return true;
}

bool removeLabwcTheme(const QString &dir, QString *error)
{
    QDir target(dir);
    if (!QFileInfo::exists(target.filePath(MarkerName)))
        return true; // nothing Daytona generated
    for (const QString &name : themeFiles()) {
        const QString path = target.filePath(name);
        if (QFileInfo::exists(path) && !QFile::remove(path)) {
            if (error)
                *error = QStringLiteral("Cannot remove %1").arg(path);
            return false;
        }
    }
    if (!QFile::remove(target.filePath(MarkerName))) {
        if (error)
            *error = QStringLiteral("Cannot remove %1").arg(target.filePath(MarkerName));
        return false;
    }
    // Remove openbox-3 and the theme directory if nothing else is left.
    QDir().rmdir(dir);
    QDir().rmdir(QFileInfo(dir).absolutePath());
    return true;
}

bool reconfigureLabwc()
{
    // As "labwc --reconfigure" does: SIGHUP to the compositor named by
    // LABWC_PID, which labwc sets for the programs it starts. Signalling it
    // directly works whichever labwc binary runs the session.
    bool ok = false;
    const qint64 pid = qEnvironmentVariable("LABWC_PID").toLongLong(&ok);
    return ok && pid > 1 && ::kill(pid_t(pid), SIGHUP) == 0;
}

